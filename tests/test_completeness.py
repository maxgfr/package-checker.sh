"""Incomplete scans, feed origins and ages, git-ignored files, pruning, bun.lockb, Bash < 4.

Offline: the built-in feed chain is pointed at local files (--data-dir), and
curl, brew and bun are replaced by stubs on PATH.
"""
import json
