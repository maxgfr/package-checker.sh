class BunBinaryLockfileTests(CompletenessCase):
    def restricted_path(self):
        tools = self.root / "tools"
        tools.mkdir(exist_ok=True)
        for tool in TOOLS:
            found = shutil.which(tool)
            if found and not (tools / tool).exists():
                (tools / tool).symlink_to(found)
        return str(tools)

    def bun_lockb(self):
        self.write("project/package.json", json.dumps({"dependencies": {"demo": "1.5.0"}}))
        path = self.root / "project" / "bun.lockb"
        path.write_bytes(b"#!/usr/bin/env bun\nbun-lockfile-format-v0\n\x00\x01demo\x00\x02")
        return path

    def test_bun_lockb_is_read_through_bun(self):
        self.bun_lockb()
        self.stub("bun", '#!/bin/sh\npwd > "$BUN_CWD"\ncase "$1" in */bun.lockb) cat "$BUN_TEXT" ;; *) exit 1 ;; esac\n')
        self.write("bun.txt", YARN_V1)
        result = self.run_script("project", "--source", self.feed("pkg:npm/demo@1.5.0"), "--no-runtime-check",
                                 "--export-json", "out.json", code=1,
                                 BUN_TEXT=str(self.root / "bun.txt"), BUN_CWD=str(self.root / "bun-cwd"))
        self.assertIn("project/bun.lockb", result.stdout)
        report = self.report()
        self.assertEqual([(v["package"], v["file"]) for v in report["vulnerabilities"]],
                         [("demo@1.5.0", "project/bun.lockb")])
        self.assertFalse(report["incomplete"])
        # bun ran outside the project (no project bunfig.toml applies).
        self.assertNotEqual(Path((self.root / "bun-cwd").read_text().strip()).resolve(),
                            (self.root / "project").resolve())

    def test_bun_lockb_without_bun_is_reported_not_skipped(self):
        self.bun_lockb()
        result = self.run_script("project", "--source", self.feed("pkg:npm/other@1.0.0"), "--no-runtime-check",
                                 "--export-json", "out.json", path=self.restricted_path(), code=3)
        self.assertIn("install bun", result.stdout)
        self.assertIn("project/bun.lockb was not scanned", result.stderr)
        report = self.report()
        self.assertTrue(report["incomplete"])
        self.assertEqual(report["files"]["unsupported"], ["project/bun.lockb"])

    def test_unread_lockfile_does_not_cover_its_package_json(self):
        feed = self.feed("pkg:npm/demo@1.5.0")
        self.bun_lockb()
        cases = [("no bun", self.restricted_path(), None), ("bun fails", None, "#!/bin/sh\nexit 1\n")]
        for label, path, bun in cases:
            with self.subTest(case=label):
                if bun:
                    self.stub("bun", bun)
                result = self.run_script("project", "--source", feed, "--no-runtime-check", "--export-json",
                                         "out.json", path=path, code=1)
                self.assertNotIn("covered by a lockfile", result.stdout)
                report = self.report()
                self.assertEqual([(v["package"], v["file"]) for v in report["vulnerabilities"]],
                                 [("demo@1.5.0", "project/package.json")])
                self.assertTrue(report["incomplete"])
                self.assertEqual(report["files"]["unsupported"], ["project/bun.lockb"])
        # A bun.lockb that bun reads covers its package.json.
        self.stub("bun", '#!/bin/sh\ncat "$BUN_TEXT"\n')
        self.write("bun.txt", YARN_V1)
        result = self.run_script("project", "--source", feed, "--no-runtime-check", code=1,
                                 BUN_TEXT=str(self.root / "bun.txt"))
        self.assertIn("Skipping 1 package.json file(s) covered by a lockfile", result.stdout)
        if os.geteuid() != 0:
            (self.root / "project" / "bun.lockb").unlink()
            lock = self.write("project/package-lock.json", "{}")
            lock.chmod(0)
            self.addCleanup(lock.chmod, 0o644)
            result = self.run_script("project", "--source", feed, "--no-runtime-check", code=1)
            self.assertIn("project/package.json", result.stdout)
            self.assertIn("Cannot read this file", result.stdout)

