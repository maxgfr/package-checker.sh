class CompletenessCase(CheckerCase):
    def setUp(self):
        super().setUp()
        self.fake_bin = self.root / "fake-bin"
        self.fake_bin.mkdir()
        self.stub("curl", FAKE_CURL)
        self.stub("brew", "#!/bin/sh\nexit 1\n")
        # A copy of the script without bundled data/ next to it.
        self.script = self.root / "install" / "script.sh"
        self.script.parent.mkdir()
        shutil.copy(SCRIPT, self.script)
        self.remote = self.root / "remote"
        self.remote.mkdir()
        self.data = self.root / "feeds"
        self.data.mkdir()

    def stub(self, name, body):
        path = self.fake_bin / name
        path.write_text(body)
        path.chmod(0o755)

    def env(self, curl="offline", path=None, **extra):
        return {**os.environ, "PATH": str(self.fake_bin) + os.pathsep + (path or os.environ["PATH"]),
                "FAKE_CURL": curl, "FAKE_REMOTE": str(self.remote), **extra}

    def run_script(self, *args, code, curl="offline", path=None, script=None, **extra):
        result = subprocess.run([BASH, str(script or self.script), *map(str, args)], cwd=self.root, text=True,
                                capture_output=True, timeout=60, env=self.env(curl, path, **extra))
        self.assertEqual(result.returncode, code, result.stdout + result.stderr)
        return result

    def report(self, name="out.json"):
        return json.loads((self.root / name).read_text())

    def lockfile(self, version="1.5.0"):
        self.write("project/package-lock.json", json.dumps({"lockfileVersion": 3, "packages": {
            "": {}, "node_modules/demo": {"version": version}}}))

    def age(self, path, days):
        stamp = time.time() - days * 86400
        os.utime(path, (stamp, stamp))


