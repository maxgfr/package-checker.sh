import unittest

from test_regressions import BASH, ROOT, SCRIPT, CheckerCase

# Answers HEAD probes and downloads from $FAKE_REMOTE (a directory standing
# for the published feeds); FAKE_CURL=offline fails like a missing network.
FAKE_CURL = r'''#!/bin/sh
[ "${FAKE_CURL:-offline}" = offline ] && exit 7
out="" url="" head=""
while [ $# -gt 0 ]; do
    case "$1" in
        -o) out="$2"; shift 2 ;;
        --head) head=1; shift ;;
        --output|--connect-timeout|--max-time|-H) shift 2 ;;
        -*) shift ;;
        *) url="$1"; shift ;;
    esac
done
file="$FAKE_REMOTE/${url##*/}"
[ -f "$file" ] || exit 22
[ -n "$head" ] && exit 0
[ "${FAKE_CURL}" = head-only ] && exit 22
if [ -n "$out" ]; then cp "$file" "$out"; else cat "$file"; fi
'''

YARN_V1 = '''# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
# bun ./bun.lockb --hash: 0000


demo@1.5.0:
  version "1.5.0"
  resolved "https://registry.npmjs.org/demo/-/demo-1.5.0.tgz"
'''

TOOLS = ["bash", "awk", "find", "git", "sort", "sed", "tr", "wc", "grep", "dirname", "basename", "mktemp", "rm",
         "xargs", "tail", "head", "cat", "stat", "date", "mv", "chmod", "cut", "readlink", "uniq", "ls", "mkdir", "cp"]


class CompletenessCase(CheckerCase):
    def setUp(self):
        super().setUp()
        self.fake_bin = self.root / "fake-bin"
        self.fake_bin.mkdir()
        self.stub("curl", FAKE_CURL)
        self.stub("brew", "#!/bin/sh\nexit 1\n")
        # A copy of the script without bundled data/ next to it.
        self.script = self.root / "install" / "script.sh"
        self.script.parent.mkdir()
        shutil.copy(SCRIPT, self.script)
        self.remote = self.root / "remote"
        self.remote.mkdir()
        self.data = self.root / "feeds"
        self.data.mkdir()

    def stub(self, name, body):
        path = self.fake_bin / name
        path.write_text(body)
        path.chmod(0o755)

    def env(self, curl="offline", path=None, **extra):
        return {**os.environ, "PATH": str(self.fake_bin) + os.pathsep + (path or os.environ["PATH"]),
                "FAKE_CURL": curl, "FAKE_REMOTE": str(self.remote), **extra}

    def run_script(self, *args, code, curl="offline", path=None, script=None, **extra):
        result = subprocess.run([BASH, str(script or self.script), *map(str, args)], cwd=self.root, text=True,
                                capture_output=True, timeout=60, env=self.env(curl, path, **extra))
        self.assertEqual(result.returncode, code, result.stdout + result.stderr)
        return result

    def report(self, name="out.json"):
        return json.loads((self.root / name).read_text())

    def lockfile(self, version="1.5.0"):
        self.write("project/package-lock.json", json.dumps({"lockfileVersion": 3, "packages": {
            "": {}, "node_modules/demo": {"version": version}}}))

    def age(self, path, days):
        stamp = time.time() - days * 86400
        os.utime(path, (stamp, stamp))


class IncompleteFeedTests(CompletenessCase):
    def test_missing_osv_feed_is_reported_in_every_output(self):
        self.lockfile()
        (self.data / "ghsa.purl").write_text("pkg:npm/demo@1.5.0?ghsa=GHSA-demo&severity=high&source=ghsa\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data,
                                 "--export-json", "out.json", code=1)
        self.assertIn("Unable to find osv feed for npm (osv.purl)", result.stdout)
        self.assertIn("Scan incomplete", result.stderr)
        self.assertIn("the osv feed for npm (osv.purl) could not be found", result.stderr)
        report = self.report()
        self.assertTrue(report["incomplete"])
        self.assertEqual(len(report["vulnerabilities"]), 1)
        sources = {source["kind"]: source for source in report["sources"]}
        self.assertEqual(sources["osv"]["status"], "missing")
        self.assertIsNone(sources["osv"]["origin"])
        self.assertEqual(sources["ghsa"]["status"], "loaded")
        self.assertEqual(sources["ghsa"]["origin"], str(self.data / "ghsa.purl"))
        self.assertEqual(sources["ghsa"]["origin_type"], "local")
        self.assertEqual(sources["ghsa"]["entries"], 1)
        self.assertEqual(sources["ghsa"]["age_days"], 0)
        self.assertFalse(sources["ghsa"]["stale"])
        self.assertRegex(sources["ghsa"]["date"], r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$")

    def test_incomplete_scan_without_finding_exits_3(self):
        self.lockfile()
        (self.data / "ghsa.purl").write_text("pkg:npm/other@1.0.0?source=ghsa\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data, code=3)
        self.assertIn("Scan incomplete", result.stderr)

    def test_complete_scan_keeps_0_and_reports_complete(self):
        self.lockfile()
        for name in ("ghsa.purl", "osv.purl"):
            (self.data / name).write_text("pkg:npm/other@1.0.0\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data,
                                 "--export-json", "out.json", code=0)
        self.assertNotIn("Scan incomplete", result.stderr)
        report = self.report()
        self.assertFalse(report["incomplete"])
        self.assertEqual(report["incomplete_reasons"], [])
        self.assertEqual([s["status"] for s in report["sources"]], ["loaded", "loaded"])

    def test_strict_stops_before_scanning(self):
        self.lockfile()
        (self.data / "ghsa.purl").write_text("pkg:npm/demo@1.5.0?source=ghsa\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data,
                                 "--strict", "--export-json", "out.json", code=3)
        self.assertIn("--strict", result.stdout)
        self.assertNotIn("Analyzing", result.stdout)
        report = self.report()
        self.assertTrue(report["incomplete"])
        self.assertEqual(report["vulnerabilities"], [])

    def test_strict_with_findings_and_unreadable_file_exits_3(self):
        if os.geteuid() == 0:
            self.skipTest("root reads every file")
        self.lockfile()
        locked = self.write("project/sub/yarn.lock", 'other@^1.0.0:\n  version "1.0.0"\n')
        locked.chmod(0)
        self.addCleanup(locked.chmod, 0o644)
        feed = self.feed("pkg:npm/demo@1.5.0")
        self.run_script("project", "--source", feed, code=1)
        self.run_script("project", "--source", feed, "--strict", code=3)

    def test_feed_that_fails_to_download_is_incomplete_not_fatal(self):
        self.lockfile()
        (self.data / "ghsa.purl").write_text("pkg:npm/other@1.0.0\n")
        (self.remote / "osv.purl").write_text("pkg:npm/demo@1.5.0\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data,
                                 "--export-json", "out.json", curl="head-only", code=3)
        self.assertIn("could not be loaded", result.stderr)
        source = self.report()["sources"][1]
        self.assertEqual((source["kind"], source["status"], source["origin_type"]), ("osv", "failed", "remote"))
        # No feed at all is not a scan: usage/environment error.
        (self.data / "ghsa.purl").unlink()
        self.run_script("project", "--no-config", "--default-source-ghsa-osv", "--data-dir", self.data, code=2)

    def test_custom_sources_are_listed(self):
        self.lockfile()
        feed = self.feed("pkg:npm/demo@1.5.0")
        self.run_script("project", "--source", feed, "--export-json", "out.json", code=1)
        source = self.report()["sources"][0]
        self.assertEqual((source["kind"], source["status"], source["origin"], source["entries"]),
                         ("custom", "loaded", str(feed), 1))
        self.assertIsNone(source["file"])


class FeedOriginTests(CompletenessCase):
    def test_data_dir_wins_over_bundled_feeds(self):
        self.lockfile()
        (self.data / "ghsa.purl").write_text("pkg:npm/demo@1.5.0?ghsa=GHSA-from-data-dir\n")
        for option in (["--data-dir", self.data], []):
            extra = {} if option else {"PACKAGE_CHECKER_DATA_DIR": str(self.data)}
            with self.subTest(option=bool(option)):
                result = self.run_script("project", "--no-config", "--default-source-ghsa", *option,
                                         script=SCRIPT, code=1, **extra)
                self.assertIn("Using GHSA source: %s/ghsa.purl" % self.data, result.stdout)
                self.assertIn("GHSA-from-data-dir", result.stdout)

    def test_stale_local_feed_is_replaced_by_a_download(self):
        self.lockfile()
        stale = self.data / "ghsa.purl"
        stale.write_text("pkg:npm/other@1.0.0\n")
        self.age(stale, 10)
        (self.remote / "ghsa.purl").write_text("pkg:npm/demo@1.5.0?id=MAL-fresh&source=ghsa\n")
        result = self.run_script("project", "--no-config", "--default-source-ghsa", "--data-dir", self.data,
                                 "--export-json", "out.json", curl="online", code=1)
        self.assertIn("older than 2 day(s)", result.stderr)
        self.assertIn("MAL-fresh", result.stdout)
        source = self.report()["sources"][0]
        self.assertEqual(source["origin"],
                         "https://raw.githubusercontent.com/maxgfr/package-checker.sh/refs/heads/main/data/ghsa.purl")
        self.assertEqual((source["origin_type"], source["stale"]), ("remote", False))

    def test_stale_local_feed_is_used_offline_with_a_warning(self):
        self.lockfile()
        stale = self.data / "ghsa.purl"
        stale.write_text("pkg:npm/demo@1.5.0\n")
        self.age(stale, 10)
        result = self.run_script("project", "--no-config", "--default-source-ghsa", "--data-dir", self.data,
                                 "--export-json", "out.json", code=1)
        self.assertIn("10 day(s) old", result.stderr)
        source = self.report()["sources"][0]
        self.assertEqual((source["origin"], source["age_days"], source["stale"]), (str(stale), 10, True))

    def test_max_feed_age(self):
        self.lockfile()
        feed = self.data / "ghsa.purl"
        feed.write_text("pkg:npm/demo@1.5.0\n")
        self.age(feed, 3)
        (self.remote / "ghsa.purl").write_text("pkg:npm/demo@1.5.0?id=MAL-remote\n")
        for max_age, expected in (("5", str(feed)), ("0", str(feed)), ("1", "https://")):
            with self.subTest(max_age=max_age):
                self.run_script("project", "--no-config", "--default-source-ghsa", "--data-dir", self.data,
                                "--max-feed-age", max_age, "--export-json", "out.json", curl="online", code=1)
                self.assertTrue(self.report()["sources"][0]["origin"].startswith(expected))
        self.run_script("--max-feed-age", "two", code=2)

    def test_update_feeds_downloads_atomically(self):
        for name in ("ghsa.purl", "osv.purl", "osv-runtime.purl"):
            (self.remote / name).write_text("pkg:npm/demo@1.5.0\n")
        target = self.root / "refresh"
        result = self.run_script("--update-feeds", "--data-dir", target, "--ecosystems", "npm", curl="online", code=0)
        self.assertEqual(sorted(p.name for p in target.iterdir()), ["ghsa.purl", "osv-runtime.purl", "osv.purl"])
        self.assertIn("Updated 3 of 3", result.stdout)
        # A failed download keeps the previous copy and exits 3.
        (self.remote / "osv.purl").unlink()
        (target / "osv.purl").write_text("previous\n")
        self.run_script("--update-feeds", "--data-dir", target, "--ecosystems", "npm", curl="online", code=3)
        self.assertEqual((target / "osv.purl").read_text(), "previous\n")
        self.assertEqual([p.name for p in target.iterdir() if p.name.startswith(".")], [])
        self.run_script("--update-feeds", code=2)


class ExitCodeTests(CompletenessCase):
    def test_unexpected_failure_exits_2_not_1(self):
        self.lockfile()
        result = subprocess.run([BASH, "-c", 'source "$1"; analyze_package_lock() { false; }; shift; main "$@"',
                                 "test", str(SCRIPT), "project", "--source", str(self.feed("pkg:npm/demo@1.5.0"))],
                                cwd=self.root, text=True, capture_output=True, timeout=30)
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)

    def test_old_bash_fails_with_install_instructions(self):
        shells = ["sh"]
        if os.path.exists("/bin/bash"):
            version = subprocess.run(["/bin/bash", "-c", "echo ${BASH_VERSINFO[0]}"], capture_output=True, text=True)
            if version.stdout.strip() in ("2", "3"):
                shells.append("/bin/bash")
        for shell in shells:
            with self.subTest(shell=shell):
                result = subprocess.run([shell, str(SCRIPT), "--help"], capture_output=True, text=True, timeout=10)
                if shell == "sh" and result.returncode == 0:
                    continue  # sh is a Bash >= 4 here
                self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
                self.assertIn("requires Bash 4 or newer", result.stderr)
                self.assertIn("brew install bash", result.stderr)
                self.assertIn('"$(brew --prefix)/bin/bash"', result.stderr)
                self.assertIn("apt-get install bash", result.stderr)


class PruneTests(CompletenessCase):
    def test_non_project_trees_are_pruned_by_default(self):
        feed = self.feed("pkg:npm/demo@1.5.0")
        for tree in (".cache/pkg", ".npm/_cacache", ".pnpm-store/v3", ".cargo/registry/src",
                     ".gradle/caches", ".m2/repository", ".venv/lib/python3.12/site-packages/x", "__pycache__",
                     ".next/server", ".nuxt/dist", "ios/Pods/x", "DerivedData/App", ".Trash/old", ".rustup/x"):
            with self.subTest(tree=tree):
                project = self.write("home/%s/package.json" % tree, json.dumps({"dependencies": {"demo": "1.5.0"}}))
                self.run_script("home", "--source", feed, "--no-runtime-check", code=0)
                self.assertIn("demo@1.5.0", self.run_script("home", "--source", feed, "--no-runtime-check",
                                                            "--no-default-prune", code=1).stdout)
                project.unlink()

    def test_home_library_is_pruned_but_not_a_project_library(self):
        feed = self.feed("pkg:npm/demo@1.5.0")
        home = self.root / "home"
        self.write("home/Library/Caches/x/package.json", json.dumps({"dependencies": {"demo": "1.5.0"}}))
        self.run_script(home, "--source", feed, "--no-runtime-check", code=0, HOME=str(home))
        self.run_script(self.root, "--source", feed, "--no-runtime-check", code=0, HOME=str(home))
        self.write("home/code/Library/package.json", json.dumps({"dependencies": {"demo": "1.5.0"}}))
        output = self.run_script(home, "--source", feed, "--no-runtime-check", code=1, HOME=str(home)).stdout
        self.assertIn("code/Library/package.json", output)
        self.assertNotIn("Caches", output)


class BunBinaryLockfileTests(CompletenessCase):
    def restricted_path(self):
        tools = self.root / "tools"
        tools.mkdir(exist_ok=True)
        for tool in TOOLS:
            found = shutil.which(tool)
            if found and not (tools / tool).exists():
                (tools / tool).symlink_to(found)
        return str(tools)

    def bun_lockb(self):
        self.write("project/package.json", json.dumps({"dependencies": {"demo": "1.5.0"}}))
        path = self.root / "project" / "bun.lockb"
        path.write_bytes(b"#!/usr/bin/env bun\nbun-lockfile-format-v0\n\x00\x01demo\x00\x02")
        return path

    def test_bun_lockb_is_read_through_bun(self):
        self.bun_lockb()
        self.stub("bun", '#!/bin/sh\npwd > "$BUN_CWD"\ncase "$1" in */bun.lockb) cat "$BUN_TEXT" ;; *) exit 1 ;; esac\n')
        self.write("bun.txt", YARN_V1)
        result = self.run_script("project", "--source", self.feed("pkg:npm/demo@1.5.0"), "--no-runtime-check",
                                 "--export-json", "out.json", code=1,
                                 BUN_TEXT=str(self.root / "bun.txt"), BUN_CWD=str(self.root / "bun-cwd"))
        self.assertIn("project/bun.lockb", result.stdout)
        report = self.report()
        self.assertEqual([(v["package"], v["file"]) for v in report["vulnerabilities"]],
                         [("demo@1.5.0", "project/bun.lockb")])
        self.assertFalse(report["incomplete"])
        # bun ran outside the project (no project bunfig.toml applies).
        self.assertNotEqual(Path((self.root / "bun-cwd").read_text().strip()).resolve(),
                            (self.root / "project").resolve())

    def test_bun_lockb_without_bun_is_reported_not_skipped(self):
        self.bun_lockb()
        result = self.run_script("project", "--source", self.feed("pkg:npm/other@1.0.0"), "--no-runtime-check",
                                 "--export-json", "out.json", path=self.restricted_path(), code=3)
        self.assertIn("install bun", result.stdout)
        self.assertIn("project/bun.lockb was not scanned", result.stderr)
        report = self.report()
        self.assertTrue(report["incomplete"])
        self.assertEqual(report["files"]["unsupported"], ["project/bun.lockb"])

    def test_unreadable_bun_lockb_is_reported(self):
        self.bun_lockb()
        self.stub("bun", "#!/bin/sh\necho 'error parsing lockfile: InvalidLockfile' >&2\nexit 1\n")
        result = self.run_script("project", "--source", self.feed("pkg:npm/other@1.0.0"), "--no-runtime-check",
                                 code=3)
        self.assertIn("bun could not print it", result.stdout)

    def test_bun_lockb_beside_bun_lock_is_skipped(self):
        self.bun_lockb()
        self.write("project/bun.lock", '{\n  "lockfileVersion": 1,\n  "packages": {\n'
                                       '    "demo": ["demo@1.5.0", "", {}, "sha512-x"],\n  }\n}\n')
        self.stub("bun", "#!/bin/sh\nexit 1\n")
        result = self.run_script("project", "--source", self.feed("pkg:npm/demo@1.5.0"), "--no-runtime-check",
                                 "--export-json", "out.json", code=1)
        self.assertIn("bun uses the bun.lock beside it", result.stdout)
        self.assertFalse(self.report()["incomplete"])

    @unittest.skipUnless(shutil.which("bun"), "bun is not installed")
    def test_real_bun_lockb_fixture(self):
        fixture = ROOT / "test-fixtures" / "bun-binary-project"
        result = subprocess.run([BASH, str(SCRIPT), str(fixture), "--source", str(self.feed("pkg:npm/lodash@4.17.20")),
                                 "--no-runtime-check", "--no-config"],
                                cwd=self.root, text=True, capture_output=True, timeout=60)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("lodash@4.17.20", result.stdout)
        self.assertIn("bun-binary-project/bun.lockb", result.stdout)


